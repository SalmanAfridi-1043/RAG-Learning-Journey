# )

client = OpenAI(
    api_key=os.getenv("OPENAI_API_KEY"),
    base_url="https://api.openai.com/v1",
)

# MODEL = "nvidia/nemotron-3.5-super-vl:free"
# MODEL = "nvidia/nemotron-3.5-lightning:free"
# MODEL = "nvidia/nemotron-3-nano-omni-30b-a3b-reasoning:free"
MODEL = "gpt-4o-mini"


messages = [{"role": "system", "content": "You are a helpfull AI RAG assistant."}]


def chat(input_prompt: str) -> str:
    messages.append({"role": "user", "content": input_prompt})

    # answer stores the final answer from the assistant
    answer = ""

    try:
        # stream uses the OpenAI streaming API to get the response in chunks
        stream = client.chat.completions.create(
            model=MODEL,
            messages=messages,
            temperature=0.7,
            max_tokens=1500,
            stream=True,
        )

        # print the assistant's response in real-time as it is generated
        print("Assistant: ", end="", flush=True)

        # iterate over the chunks of the response and print them as they are received
        for chunk in stream:
            if not chunk.choices:
                continue

            # get the delta from the chunk, which contains the new content generated by the model
            delta = chunk.choices[0].delta

            # reasoning is used to get the reasoning behind the model's response, if available.
            # reasoning = getattr(delta, "reasoning", None)
            # if reasoning:
            #     print(reasoning, end="", flush=True)

            # the actual asnwer which is generated by the model.
            if delta.content:
                print(delta.content, end="", flush=True)
                answer += delta.content

        # print line after the assistant's response is complete
        print()

        if answer:
            messages.append({"role": "assistant", "content": answer})
        else:
            messages.pop()

        # return answer

    except Exception as e:
        print("\nError:", e)
        messages.pop()
        return ""


while True:
    userInput = input("\nUser : ")
    if userInput.lower() == "exit":
        break
    chat(userInput)
