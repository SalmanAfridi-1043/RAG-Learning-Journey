from openai import OpenAI
import os
from dotenv import load_dotenv

load_dotenv()

MODEL = "nvidia/nemotron-3.5-super-vl:free"

client = OpenAI(
    api_key=os.getenv("OPENROUTER_API_KEY"), base_url="https://openrouter.ai/api/v1"
)


# Unstructured Output
messages = [
    {
        "role": "user",
        "content": """
        Tell me about a student named Salman,
        age 22, who knows Python and Java.
        """,
    }
]

response = client.chat.completions.create(model=MODEL, messages=messages)

print("UNSTRUCTURED OUTPUT : ")
print(response.choices[0].message.content)


print()
print()

# Structured Output
messages = [
    {
        "role": "user",
        "content": """
        Tell me about a student named Salman,
        age 22, who knows Python and Java.

        Return the information in JSON format with:
        name, age, and skills.
        """,
    }
]

response = client.chat.completions.create(model=MODEL, messages=messages)

print("\nSTRUCTURED OUTPUT:")
print(response.choices[0].message.content)


# What did we learn:
# - First request: Model generates normal text.
# - Second request: We instruct the model to generate JSON.
# - Both are generated by the same LLM.
# - The difference is the output format.
